#!/usr/bin/env python3
"""Generate the Phase 3 river demo tile set and nametable row stream.

The Atari playfield is an ANTIC mode-E bitmap: each byte holds four 2-bit
pixels, so two bytes describe one 8-pixel NES tile *row* (one scanline).
A NES background tile is 8 scanlines tall, i.e. eight consecutive Atari rows.
The captured 157-row river fixture is 48 bytes wide; bytes 4..43 are the
visible 40-byte (160-pixel) window, which becomes exactly 20 NES tiles.

The generator packs the fixture into full 8-scanline tile rows, deduplicates
the resulting 8x8 tiles, and emits:

* one interleaved 2bpp CHR tile per distinct 8x8 tile,
* the fixture converted to 20 relative tile indices per tile row,
* the relative index of the solid-land tile, used for the side margins.

Run:  python tools/gen_river_demo.py
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "assets" / "atari" / "extracted" / "river_rows_157.bin"
HEADER = ROOT / "src" / "river_demo_data.h"
SOURCE = ROOT / "src" / "river_demo_data.c"

VISIBLE_X = 4
VISIBLE_BYTES = 40
TILES_PER_ROW = VISIBLE_BYTES // 2
TILE_ROWS = 19  # 19 * 8 = 152 of the 157 captured scanlines


def scanline_pixels(byte: int) -> list[int]:
    """Four 2-bit pixels, left to right."""
    return [(byte >> (6 - 2 * i)) & 0x03 for i in range(4)]


def make_tile(rows: list[bytes], tile_x: int) -> tuple[int, ...]:
    """Return the 64 pixel values of one 8x8 tile."""
    pixels: list[int] = []
    for y in range(8):
        visible = rows[y][VISIBLE_X : VISIBLE_X + VISIBLE_BYTES]
        for k in range(2):
            pixels.extend(scanline_pixels(visible[tile_x * 2 + k]))
    return tuple(pixels)


def chr_tile(pixels: tuple[int, ...]) -> list[int]:
    """Convert 64 pixel values to GBDK's interleaved 2bpp tile format."""
    data: list[int] = []
    for y in range(8):
        plane0 = 0
        plane1 = 0
        for x in range(8):
            value = pixels[y * 8 + x]
            plane0 = (plane0 << 1) | (value & 1)
            plane1 = (plane1 << 1) | ((value >> 1) & 1)
        data.extend((plane0, plane1))
    return data


def c_bytes(values: list[int], per_line: int = 16) -> str:
    lines = []
    for i in range(0, len(values), per_line):
        chunk = values[i : i + per_line]
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in chunk) + ",")
    return "\n".join(lines)


def main() -> None:
    raw = FIXTURE.read_bytes()
    source_rows = [raw[i * 48 : (i + 1) * 48] for i in range(len(raw) // 48)]

    tiles: list[tuple[int, ...]] = []
    tile_index: dict[tuple[int, ...], int] = {}
    row_tiles: list[int] = []

    for tile_row in range(TILE_ROWS):
        rows = source_rows[tile_row * 8 : tile_row * 8 + 8]
        assert len(rows) == 8
        for tile_x in range(TILES_PER_ROW):
            key = make_tile(rows, tile_x)
            if key not in tile_index:
                tile_index[key] = len(tiles)
                tiles.append(key)
            row_tiles.append(tile_index[key])

    # Solid green land: every pixel value 1 (COLBK/COLPF mapping: 1 = bank).
    land = tuple([1] * 64)
    if land not in tile_index:
        # The bottom of the fixture may not contain a pure land tile; append it.
        tile_index[land] = len(tiles)
        tiles.append(land)

    chr_data: list[int] = []
    for tile in tiles:
        chr_data.extend(chr_tile(tile))

    assert len(chr_data) == len(tiles) * 16
    assert len(row_tiles) == TILE_ROWS * TILES_PER_ROW

    HEADER.write_text(
        f"""/*
 * river_demo_data.h - generated by tools/gen_river_demo.py. Do not edit.
 *
 * Phase 3 scrolling demo: the captured Atari river packed into 8x8 NES
 * background tiles.  Each tile row is 20 tiles (the visible 160-pixel
 * mode-E window); the port adds six solid-land tiles on each side to fill
 * 32 columns.
 */
#ifndef RIVER_DEMO_DATA_H
#define RIVER_DEMO_DATA_H

#define RIVER_DEMO_TILE_ROWS    {TILE_ROWS}u
#define RIVER_DEMO_TILE_COUNT   {len(tiles)}u
#define RIVER_DEMO_TILES_W      {TILES_PER_ROW}u
#define RIVER_DEMO_TILE_LAND    {tile_index[land]}u

/* One interleaved 2bpp tile per distinct 8x8 playfield tile. */
extern const unsigned char river_demo_tile_chr[RIVER_DEMO_TILE_COUNT * 16];

/* Relative tile index for each of the 20 visible tiles per tile row. */
extern const unsigned char river_demo_row_tiles[RIVER_DEMO_TILE_ROWS * RIVER_DEMO_TILES_W];

#endif /* RIVER_DEMO_DATA_H */
""",
        encoding="utf-8",
    )

    SOURCE.write_text(
        f"""/* Generated by tools/gen_river_demo.py. */
#include "river_demo_data.h"

/* Interleaved 2bpp CHR for each distinct playfield tile. */
const unsigned char river_demo_tile_chr[RIVER_DEMO_TILE_COUNT * 16] = {{
{c_bytes(chr_data)}
}};

/* Fixture tile rows as relative tile indices. */
const unsigned char river_demo_row_tiles[RIVER_DEMO_TILE_ROWS * RIVER_DEMO_TILES_W] = {{
{c_bytes(row_tiles, 20)}
}};
""",
        encoding="utf-8",
    )

    print(
        f"wrote {HEADER.name}: {TILE_ROWS} tile rows, "
        f"{len(tiles)} tiles, land index {tile_index[land]}"
    )
    print(f"wrote {SOURCE.name}: {len(chr_data)} CHR bytes, {len(row_tiles)} row bytes")


if __name__ == "__main__":
    main()
