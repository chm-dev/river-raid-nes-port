"""Generate src/river_lut.h: mode-E byte -> NES 2bpp plane nibbles."""
import pathlib
def nib(b, plane):
    n = 0
    for i in range(4):
        v = (b >> (6 - 2 * i)) & 3
        n = (n << 1) | ((v >> plane) & 1)
    return n
def table(name, plane):
    rows = []
    for r in range(0, 256, 16):
        rows.append("    " + ", ".join("0x%02X" % nib(b, plane) for b in range(r, r + 16)) + ",")
    return "static const uint8_t %s[256] = {\n%s\n};\n" % (name, "\n".join(rows))
out = ("/* Generated by tools/gen_river_lut.py - do not edit.\n"
       " * Mode-E byte (4 pixels, 2 bits each) -> 4-bit NES plane nibble. */\n"
       "#ifndef RIVER_LUT_H\n#define RIVER_LUT_H\n#include <stdint.h>\n\n"
       + table("river_lut_p0", 0) + "\n" + table("river_lut_p1", 1) + "\n#endif\n")
pathlib.Path(__file__).resolve().parent.parent.joinpath("src", "river_lut.h").write_text(out)
